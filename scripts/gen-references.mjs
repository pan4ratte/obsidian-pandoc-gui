/*
 * Regenerates `src/pandoc/reference_data.ts` from the three documents in
 * `reference-docs/`.
 *
 * The plugin carries Pandoc's reference documents as base64 in a source module
 * rather than reading them out of `reference-docs/` while the bundle is built.
 * Nothing in the linted tree may import node — the plugin runs on a phone, and
 * Obsidian's review linter says so for every file in the repository, whatever
 * `eslint.config.js` exempts locally — and a generated module needs no reading
 * at all. This script is maintainer tooling, run from a terminal, and is never
 * part of the plugin.
 *
 * Run it whenever the documents are reprinted for a new Pandoc release; see
 * "Refreshing the reference documents" in docs/CONTRIBUTING.md.
 *
 *   node scripts/gen-references.mjs           rewrites the module
 *   node scripts/gen-references.mjs --check   fails if it is out of date
 */

import { readFileSync, writeFileSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const target = join(root, 'src', 'pandoc', 'reference_data.ts');

/** The writers that take a reference document — `REFERENCE_FORMATS` in src/pandoc/reference_doc.ts. */
const FORMATS = ['docx', 'odt', 'pptx'];

const HEADER = `/* Pandoc's reference documents, as base64 — generated by scripts/gen-references.mjs, not written by hand.
 *
 * They are a source module rather than a build-time read of \`reference-docs/\` because nothing in this tree may import
 * node: the plugin runs on a phone, and Obsidian's review linter says so for every file in the repository, whatever a
 * local eslint config exempts. A generated module needs no reading at all.
 *
 * Regenerate with \`npm run gen:references\` whenever the files in \`reference-docs/\` are reprinted.
 */
`;

const generate = () =>
  HEADER +
  FORMATS.map(format => {
    const base64 = readFileSync(join(root, 'reference-docs', `reference.${format}`)).toString('base64');
    return `\nexport const ${format} =\n  '${base64}';\n`;
  }).join('');

const wanted = generate();

if (process.argv.includes('--check')) {
  const found = readFileSync(target, 'utf8');
  if (found !== wanted) {
    console.error('src/pandoc/reference_data.ts is out of date with reference-docs/. Run: npm run gen:references');
    process.exit(1);
  }
  console.log('src/pandoc/reference_data.ts matches reference-docs/.');
} else {
  writeFileSync(target, wanted);
  console.log(`Wrote src/pandoc/reference_data.ts from ${FORMATS.length} documents.`);
}
